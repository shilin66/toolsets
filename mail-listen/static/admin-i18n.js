const I18N_MESSAGES = {
  "zh-CN": I18N_MESSAGES_ZH_CN,
  en: I18N_MESSAGES_EN,
  "zh-HK": I18N_MESSAGES_ZH_HK,
};

// ==================== 初始语言解析 ====================
// localStorage 记忆优先，其次按浏览器语言匹配，其余回退 zh-CN
function detectInitialLang() {
  const saved = localStorage.getItem(I18N_LANG_KEY);
  if (I18N_SUPPORTED_LANGS.includes(saved)) {
    return saved;
  }
  const nav = (navigator.language || "").toLowerCase();
  if (nav === "zh-hk" || nav === "zh-mo") {
    return "zh-HK";
  }
  if (nav.startsWith("zh")) {
    return "zh-CN";
  }
  if (nav.startsWith("en")) {
    return "en";
  }
  return "zh-CN";
}

// ==================== i18n 实例 ====================
const i18n = VueI18n.createI18n({
  legacy: false,
  globalInjection: true,
  locale: detectInitialLang(),
  fallbackLocale: "zh-CN",
  messages: I18N_MESSAGES,
  missingWarn: false,
  fallbackWarn: false,
});

const EP_LOCALE_MAP = {
  "zh-CN": ElementPlusLocaleZhCn,
  en: ElementPlusLocaleEn,
  "zh-HK": ElementPlusLocaleZhHk,
};
const epLocale = Vue.ref(EP_LOCALE_MAP[i18n.global.locale.value]);

// JS 逻辑中使用的翻译函数（模板中可直接用 $t）
function tt(key, params) {
  return i18n.global.t(key, params || {});
}

function hasI18nKey(key) {
  return i18n.global.te(key);
}

function currentLang() {
  return i18n.global.locale.value;
}

function applyLangSideEffects(lang) {
  document.documentElement.lang = I18N_HTML_LANG[lang] || lang;
  document.title = tt("common.docTitle");
}

function setLocale(lang) {
  if (!I18N_SUPPORTED_LANGS.includes(lang)) {
    return;
  }
  i18n.global.locale.value = lang;
  localStorage.setItem(I18N_LANG_KEY, lang);
  epLocale.value = EP_LOCALE_MAP[lang];
  applyLangSideEffects(lang);
}

applyLangSideEffects(i18n.global.locale.value);

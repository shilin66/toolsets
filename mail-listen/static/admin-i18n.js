// JS 逻辑中使用的翻译函数（模板中可直接用 $t）
function tt(key, params) {
  return i18n.global.t(key, params || {});
}

function hasI18nKey(key) {
  return i18n.global.te(key);
}

function currentLang() {
  return i18n.global.locale.value;
}

function applyLangSideEffects(lang) {
  document.documentElement.lang = I18N_HTML_LANG[lang] || lang;
  document.title = tt("common.docTitle");
}

function setLocale(lang) {
  if (!I18N_SUPPORTED_LANGS.includes(lang)) {
    return;
  }
  i18n.global.locale.value = lang;
  localStorage.setItem(I18N_LANG_KEY, lang);
  epLocale.value = EP_LOCALE_MAP[lang];
  applyLangSideEffects(lang);
}

